"""Retrieval quality evaluation — precision/recall/MRR/nDCG over query→key cases.

The metric functions are pure and take a ``search_fn`` (query -> ranked keys),
so the harness has no dependency on the embedding backend and is fully testable.
Cases come either from a profile's ``eval_cases.json`` or are self-generated by
turning each memory's own content into a query that should retrieve it.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Dict, List, Sequence

from ..storage.memory import Memory


@dataclass
class EvalCase:
    query: str
    relevant_keys: List[str]


def precision_at_k(ranked: Sequence[str], relevant: set, k: int) -> float:
    topk = ranked[:k]
    if not topk:
        return 0.0
    return sum(1 for x in topk if x in relevant) / len(topk)


def recall_at_k(ranked: Sequence[str], relevant: set, k: int) -> float:
    if not relevant:
        return 0.0
    topk = set(ranked[:k])
    return sum(1 for r in relevant if r in topk) / len(relevant)


def reciprocal_rank(ranked: Sequence[str], relevant: set) -> float:
    for i, x in enumerate(ranked):
        if x in relevant:
            return 1.0 / (i + 1)
    return 0.0


def ndcg_at_k(ranked: Sequence[str], relevant: set, k: int) -> float:
    dcg = 0.0
    for i, x in enumerate(ranked[:k]):
        if x in relevant:
            dcg += 1.0 / math.log2(i + 2)
    ideal_hits = min(len(relevant), k)
    idcg = sum(1.0 / math.log2(i + 2) for i in range(ideal_hits))
    return dcg / idcg if idcg else 0.0


def evaluate(cases: List[EvalCase], search_fn: Callable[[str], Sequence[str]],
             k: int = 10) -> Dict[str, float]:
    """Run search_fn over every case and average the ranking metrics."""
    if not cases:
        return {"cases": 0, "k": k, "precision": 0.0, "recall": 0.0, "mrr": 0.0, "ndcg": 0.0}
    p = r = rr = nd = 0.0
    for case in cases:
        ranked = list(search_fn(case.query))
        rel = set(case.relevant_keys)
        p += precision_at_k(ranked, rel, k)
        r += recall_at_k(ranked, rel, k)
        rr += reciprocal_rank(ranked, rel)
        nd += ndcg_at_k(ranked, rel, k)
    n = len(cases)
    return {
        "cases": n,
        "k": k,
        "precision": round(p / n, 4),
        "recall": round(r / n, 4),
        "mrr": round(rr / n, 4),
        "ndcg": round(nd / n, 4),
    }


def _derive_query(value: str) -> str:
    for line in value.splitlines():
        line = line.strip().lstrip("#").strip()
        if len(line) >= 12:
            return " ".join(line.split()[:12])
    words = value.split()
    return " ".join(words[:12]) if len(words) >= 3 else ""


def self_eval_cases(memories: List[Memory], sample: int = 0) -> List[EvalCase]:
    """Build self-retrieval cases: each memory's leading content as a query that
    should retrieve that memory's key. Sampling is deterministic (stride)."""
    mems = sorted([m for m in memories if len(m.value) >= 30], key=lambda m: m.key)
    if sample and sample < len(mems):
        stride = len(mems) / sample
        mems = [mems[int(i * stride)] for i in range(sample)]
    cases: List[EvalCase] = []
    for m in mems:
        q = _derive_query(m.value)
        if q:
            cases.append(EvalCase(query=q, relevant_keys=[m.key]))
    return cases


def load_cases(path: Path) -> List[EvalCase]:
    """Load user-defined cases from a JSON list of {query, relevant_keys}."""
    data = json.loads(Path(path).read_text())
    cases: List[EvalCase] = []
    for d in data:
        q = (d.get("query") or "").strip()
        keys = d.get("relevant_keys") or d.get("keys") or []
        if q and keys:
            cases.append(EvalCase(query=q, relevant_keys=list(keys)))
    return cases
